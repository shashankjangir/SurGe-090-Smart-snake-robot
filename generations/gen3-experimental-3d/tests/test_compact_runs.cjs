const test = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const path = require('node:path');
const {readAsset} = require('./asset-source.cjs');
const source = readAsset(path.join(__dirname, '../backend/web_dashboard/static/pages/gen3-run-journal.js'));
test('journal keeps every run in one scrolling table without discarding annotation drafts', () => {
  const rows = Array.from({length: 7}, (_, i) => ({hidden: i > 2, draft: 'unsaved observation'}));
  const elements = {'runs-table-body': {children: rows}, 'runs-visible-count': {}};
  const context = vm.createContext({$: id => elements[id], document: {addEventListener() {}}});
  const start = source.indexOf('const RUNS_VISIBLE = 3;');
  vm.runInContext(source.slice(start, source.indexOf('async function loadRuns()', start)), context);
  context.updateRunVisibility();
  assert.equal(rows.filter(row => !row.hidden).length, 7, 'no run is hidden behind a button');
  assert.equal(elements['runs-visible-count'].textContent, '7 runs · scroll the table for older runs');
  assert(rows.every(row => row.draft === 'unsaved observation'));
  elements['runs-table-body'].children = rows.slice(0, 1);
  context.updateRunVisibility();
  assert.equal(elements['runs-visible-count'].textContent, '1 run');
  elements['runs-table-body'].children = [];
  context.updateRunVisibility();
  assert.equal(elements['runs-visible-count'].textContent, 'No runs in this workspace.');
  assert(!source.includes("$('runs-show-more')"), 'the Show more button is gone');
});
